#!/usr/bin/env python3
"""Build the Oil Leaks database from the CSV files in data/.

Outputs:
  web/oil_leaks.db      SQLite database loaded by the live website
  db/mysql/seed.sql     INSERT statements for MySQL
  web/queries.sql       copy of db/queries.sql for the website's sample query list

Usage:  python scripts/build.py
"""
import csv
import datetime
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

# Load order matters because of foreign keys. type map: i=int, f=float, s=string
TABLES = [
    ("country", "countries.csv", {"country_id": "i"}),
    ("cause", "causes.csv", {"cause_id": "i"}),
    ("impact_type", "impact_types.csv", {"impact_type_id": "i"}),
    ("company", "companies.csv", {"company_id": "i", "country_id": "i"}),
    ("incident", "incidents.csv", {
        "incident_id": "i", "country_id": "i", "cause_id": "i",
        "latitude": "f", "longitude": "f", "volume_barrels": "i", "fatalities": "i"}),
    ("incident_company", "incident_companies.csv", {"incident_id": "i", "company_id": "i"}),
    ("incident_impact", "incident_impacts.csv", {"incident_id": "i", "impact_type_id": "i"}),
    ("source_reference", "source_references.csv", {"reference_id": "i", "incident_id": "i"}),
]


def convert(value, kind):
    if value == "":
        return None
    if kind == "i":
        return int(value)
    if kind == "f":
        return float(value)
    return value


def load_rows():
    data = {}
    for table, filename, types in TABLES:
        with open(DATA / filename, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            cols = reader.fieldnames
            rows = [tuple(convert(r[c], types.get(c, "s")) for c in cols) for r in reader]
        data[table] = (cols, rows)
    return data


def validate(data):
    """Cheap sanity checks so bad contributions fail in CI before reaching the database."""
    errors = []
    ids = {t: {r[0] for r in data[t][1]} for t in ("country", "cause", "impact_type", "company", "incident")}
    icols = data["incident"][0]
    for row in data["incident"][1]:
        rec = dict(zip(icols, row))
        label = f"incident {rec['incident_id']} ({rec['name']})"
        try:
            d = datetime.date.fromisoformat(rec["incident_date"])
            if d > datetime.date.today():
                errors.append(f"{label}: date in the future")
        except ValueError:
            errors.append(f"{label}: bad date {rec['incident_date']!r}")
        if rec["country_id"] not in ids["country"]:
            errors.append(f"{label}: unknown country_id")
        if rec["cause_id"] not in ids["cause"]:
            errors.append(f"{label}: unknown cause_id")
        if not -90 <= rec["latitude"] <= 90 or not -180 <= rec["longitude"] <= 180:
            errors.append(f"{label}: coordinates out of range")
    for table, fk_col, parent in [
        ("incident_company", "incident_id", "incident"),
        ("incident_company", "company_id", "company"),
        ("incident_impact", "incident_id", "incident"),
        ("incident_impact", "impact_type_id", "impact_type"),
        ("company", "country_id", "country"),
    ]:
        cols, rows = data[table]
        idx = cols.index(fk_col)
        for r in rows:
            if r[idx] is not None and r[idx] not in ids[parent]:
                errors.append(f"{table}.{fk_col}={r[idx]} has no matching {parent}")
    for r in data["source_reference"][1]:
        if r[1] is not None and r[1] not in ids["incident"]:
            errors.append(f"source_reference {r[0]}: unknown incident_id {r[1]}")
        if not str(r[3]).startswith(("http://", "https://")):
            errors.append(f"source_reference {r[0]}: url must start with http(s)")
    return errors


def build_sqlite(data, path):
    if path.exists():
        path.unlink()
    con = sqlite3.connect(path)
    con.executescript((ROOT / "db" / "sqlite" / "schema.sql").read_text(encoding="utf-8"))
    for table, _, _ in TABLES:
        cols, rows = data[table]
        marks = ",".join("?" * len(cols))
        con.executemany(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({marks})", rows)
    con.commit()
    con.execute("VACUUM")
    con.close()


def mysql_literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"


def build_mysql_seed(data, path):
    lines = [
        "-- Generated by scripts/build.py from the CSV files in data/. Do not edit by hand.",
        "USE oil_leaks;",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "SET NAMES utf8mb4;",
        "",
    ]
    for table, _, _ in TABLES:
        cols, rows = data[table]
        lines.append(f"-- {table}")
        lines.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
        lines.append(",\n".join("  (" + ", ".join(mysql_literal(v) for v in r) + ")" for r in rows) + ";")
        lines.append("")
    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    data = load_rows()
    errors = validate(data)
    if errors:
        print("Validation failed:")
        for e in errors:
            print("  -", e)
        sys.exit(1)
    (ROOT / "web").mkdir(exist_ok=True)
    build_sqlite(data, ROOT / "web" / "oil_leaks.db")
    build_mysql_seed(data, ROOT / "db" / "mysql" / "seed.sql")
    (ROOT / "web" / "queries.sql").write_text(
        (ROOT / "db" / "queries.sql").read_text(encoding="utf-8"), encoding="utf-8")
    counts = ", ".join(f"{t}={len(data[t][1])}" for t, _, _ in TABLES)
    print("Built web/oil_leaks.db and db/mysql/seed.sql:", counts)


if __name__ == "__main__":
    main()
